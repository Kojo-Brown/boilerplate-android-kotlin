SHA1: 00:11:22:33:44:55:66:77:88:99:AA:BB:CC:DD:EE:FF:00:11:22:33
SHA-256: $DEBUG_SHA
Valid until: Tuesday, 1 January 2055
----------
Variant: release
Config: release
Store: /home/runner/work/app/build/signing/upload-keystore.jks
