#!/usr/bin/env bash
#
# Tests for scripts/verify-upload-signing.sh.
#
# That script is itself a test — it rehearses the release signing path against a throwaway key —
# and its happy path runs on every CI build. What does not run is any of its failure paths, and
# those are the whole point: a rehearsal that would pass a build wired to no signing config, or one
# that prints a password into a log, is worse than no rehearsal, because it reports green about the
# thing it stopped checking.
#
# So this drives the real script against a stub `gradlew` and a stub `keytool` whose output is
# fixture-controlled, and shows each check failing when it should and only when it should.
#
# It needs nothing but bash: no Gradle, no Android SDK, no JDK, no network. That is deliberate.
# Neither the Android SDK nor the Android Gradle Plugin can be fetched in the environment this
# repository's scheduled agent runs in — Google Maven answers 403 on CONNECT there — so none of the
# five gates in CLAUDE.md can run, and this keeps the gate's own logic checkable anyway.
#
# Usage: scripts/verify-upload-signing.test.sh

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VERIFY="$SCRIPT_DIR/verify-upload-signing.sh"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

tests_run=0
tests_failed=0

# The certificate the stub keytool reports for the throwaway key, and the one it reports for the
# debug key. Different, because the point of the `minified` check is that the two are not the same.
THROWAWAY_SHA='AA:BB:CC:DD:EE:FF:00:11:22:33:44:55:66:77:88:99:AA:BB:CC:DD:EE:FF:00:11:22:33:44:55:66:77:88:99'
THROWAWAY_HEX='AABBCCDDEEFF00112233445566778899AABBCCDDEEFF00112233445566778899'
DEBUG_SHA='11:22:33:44:55:66:77:88:99:00:11:22:33:44:55:66:77:88:99:00:11:22:33:44:55:66:77:88:99:00:11:22'

BIN="$WORK/bin"
mkdir -p "$BIN"

# --- stub toolchain ------------------------------------------------------------------------

# Answers `-genkeypair` by creating the file at `-keystore`, and `-list` from a fixture. Both
# exit statuses come from the fixture, so "keytool is broken" is a case like any other.
cat >"$BIN/keytool" <<'STUB'
#!/usr/bin/env bash
mode=list
keystore=
previous=
for argument in "$@"; do
    case "$previous" in -keystore) keystore="$argument" ;; esac
    case "$argument" in -genkeypair) mode=genkeypair ;; esac
    previous="$argument"
done
if [ "$mode" = genkeypair ]; then
    printf 'stub keystore\n' >"$keystore"
    exit "$(cat "$FIXTURE/keytool.genkeypair.exit" 2>/dev/null || echo 0)"
fi
cat "$FIXTURE/keytool.list.out" 2>/dev/null
exit "$(cat "$FIXTURE/keytool.list.exit" 2>/dev/null || echo 0)"
STUB

# Answers the nth invocation from `gradle.<n>.out` and `gradle.<n>.exit`, so a scenario is
# expressed purely as data. The `leak` flag makes it print the password it was handed, which is the
# only way to show that the check for one can fail: the password is generated by the script under
# test and nothing here knows it in advance.
cat >"$BIN/gradlew" <<'STUB'
#!/usr/bin/env bash
count="$(cat "$FIXTURE/calls" 2>/dev/null || echo 0)"
count=$((count + 1))
printf '%s\n' "$count" >"$FIXTURE/calls"
if [ -f "$FIXTURE/leak" ]; then
    printf 'FAILURE: Build failed with an exception: storePassword=%s\n' "$UPLOAD_KEYSTORE_PASSWORD"
fi
cat "$FIXTURE/gradle.$count.out" 2>/dev/null
exit "$(cat "$FIXTURE/gradle.$count.exit" 2>/dev/null || echo 0)"
STUB

chmod +x "$BIN/keytool" "$BIN/gradlew"

# --- baseline fixture: everything wired, gated and quiet about its secrets --------------------

BASELINE="$WORK/baseline"
mkdir -p "$BASELINE"

# The two lines the real keytool prints under "Certificate fingerprints:". Only SHA256 is read, and
# SHA1 is here because it is the line immediately above it and a sloppier pattern would take it.
cat >"$BASELINE/keytool.list.out" <<EOF
Alias name: rehearsal-upload-key-not-a-real-key
Creation date: 1 Jan 2026
Entry type: PrivateKeyEntry
Certificate fingerprints:
	 SHA1: 00:11:22:33:44:55:66:77:88:99:AA:BB:CC:DD:EE:FF:00:11:22:33
	 SHA256: $THROWAWAY_SHA
