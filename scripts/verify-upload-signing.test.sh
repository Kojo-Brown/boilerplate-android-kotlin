EOF

# 1 and 2: the release lifecycle task graphs, which have to contain the gate.
for task in assembleRelease bundleRelease; do
    cat >"$BASELINE/gradle.$(if [ "$task" = assembleRelease ]; then echo 1; else echo 2; fi).out" <<EOF
:app:checkUploadSigning SKIPPED
:app:compileReleaseKotlin SKIPPED
:app:$task SKIPPED
EOF
done

# 3: the debug graph, which must not.
cat >"$BASELINE/gradle.3.out" <<'EOF'
:app:compileDebugKotlin SKIPPED
:app:packageDebug SKIPPED
:app:assembleDebug SKIPPED
EOF

# 4: no key declared.
cat >"$BASELINE/gradle.4.out" <<'EOF'
> Task :app:checkUploadSigning FAILED

FAILURE: Build failed with an exception.

* What went wrong:
Execution failed for task ':app:checkUploadSigning'.
> Release signing is not configured: gradle/upload-signing.properties declares no upload key.

  A release built without it would not fail: AGP would write an unsigned artifact and exit 0.
EOF
echo 1 >"$BASELINE/gradle.4.exit"

# 5: the key declared and present — the gate passing, and signingReport's per-variant blocks.
cat >"$BASELINE/gradle.5.out" <<EOF
> Task :app:checkUploadSigning
Play upload signing: alias \`rehearsal-upload-key-not-a-real-key\`, certificate SHA-256 $THROWAWAY_HEX

> Task :app:signingReport
Variant: debug
